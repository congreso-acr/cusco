window.openPresentationModal = function(presId) {
    const item = PRESENTACIONES.find(p => p.id === presId);
    if (!item) return;

    const modal = document.getElementById('presentation-modal');
    const titleEl = document.getElementById('modal-pres-title');
    const speakerEl = document.getElementById('modal-pres-speaker');
    const instEl = document.getElementById('modal-pres-inst');
    const dayEl = document.getElementById('modal-pres-day');
    const downloadBtn = document.getElementById('modal-pres-download-btn');
    const fullscreenBtn = document.getElementById('modal-pres-fullscreen-btn');
    const frameContainer = document.getElementById('modal-pres-frame-container');

    if (!modal) return;

    if (titleEl) titleEl.textContent = item.title;
    if (speakerEl) speakerEl.textContent = item.speaker;
    if (instEl) instEl.textContent = item.institution ? `🏢 ${item.institution}` : '';
    if (dayEl) dayEl.textContent = `${item.dayLabel} · 🕒 ${item.time}`;

    const encodedFile = encodeURI(item.file);

    if (downloadBtn) {
        downloadBtn.href = encodedFile;
        downloadBtn.setAttribute('download', item.fileName);
    }

    if (fullscreenBtn) {
        fullscreenBtn.href = encodedFile;
    }

    // Embeber iframe de PDF
    if (frameContainer) {
        frameContainer.innerHTML = `
            <iframe src="${encodedFile}#view=FitH" class="pres-pdf-iframe" title="${escapeHtml(item.title)}"></iframe>
            <div class="pres-iframe-fallback">
                <p>¿No puedes visualizar el documento en tu navegador móvil?</p>
                <a href="${encodedFile}" target="_blank" class="btn-primary" style="margin-top: 0.5rem; display: inline-block;">Abrir PDF en Pantalla Completa</a>
            </div>
        `;
    }

    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
};

window.closePresentationModal = function() {
    const modal = document.getElementById('presentation-modal');
    const frameContainer = document.getElementById('modal-pres-frame-container');
    if (modal) {
        modal.classList.remove('active');
        document.body.style.overflow = '';
        if (frameContainer) frameContainer.innerHTML = '';
    }
};

function initModalEvents() {
    const modal = document.getElementById('presentation-modal');
    const closeBtn = document.getElementById('modal-pres-close-btn');

    if (closeBtn) {
        closeBtn.addEventListener('click', window.closePresentationModal);
    }

    if (modal) {
        modal.addEventListener('click', (e) => {
            if (e.target === modal || e.target.classList.contains('pres-modal-backdrop')) {
                window.closePresentationModal();
            }
        });
    }

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && modal && modal.classList.contains('active')) {
            window.closePresentationModal();
        }
    });
}

function escapeHtml(text) {
    if (!text) return '';
    const map = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' };
    return text.replace(/[&<>"']/g, m => map[m]);
}

// Inicialización general
document.addEventListener('DOMContentLoaded', () => {
    initFilters();
    initAutocomplete();
    initModalEvents();
    renderPresentations();
});
