// FILTROS POR DÍA Y CATEGORÍA
// ==========================================
function initFilters() {
    const dayBtns = document.querySelectorAll('.pres-day-filter-btn');
    const catSelect = document.getElementById('filter-pres-category');

    dayBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            dayBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            activeDayFilter = btn.getAttribute('data-day') || 'all';
            renderPresentations();
        });
    });

    if (catSelect) {
        catSelect.addEventListener('change', () => {
            activeCategoryFilter = catSelect.value;
            renderPresentations();
        });
    }
}

