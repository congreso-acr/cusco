// Estado de la aplicación
let activeDayFilter = 'all';
let activeCategoryFilter = 'all';
let searchQuery = '';
let selectedSuggestionIndex = -1;

// ==========================================================================
// RENDERIZADO DE TARJETAS DE PRESENTACIÓN
// ==========================================================================
function renderPresentations() {
    const grid = document.getElementById('presentations-grid');
    const noResults = document.getElementById('no-presentations-message');
    const countBadge = document.getElementById('results-count-badge');
    if (!grid) return;

    const queryClean = searchQuery.toLowerCase().trim();

    const filtered = PRESENTACIONES.filter(item => {
        // Filtro por Día
        if (activeDayFilter !== 'all' && item.day.toString() !== activeDayFilter.toString()) {
            return false;
        }

        // Filtro por Eje Temático
        if (activeCategoryFilter !== 'all' && item.category !== activeCategoryFilter) {
            return false;
        }

        // Filtro por Búsqueda (Título, Ponente, Institución, Palabras clave)
        if (queryClean) {
            const matchTitle = item.title.toLowerCase().includes(queryClean);
            const matchSpeaker = item.speaker.toLowerCase().includes(queryClean);
            const matchInst = item.institution.toLowerCase().includes(queryClean);
            const matchKeywords = item.keywords && item.keywords.some(k => k.toLowerCase().includes(queryClean));
            if (!matchTitle && !matchSpeaker && !matchInst && !matchKeywords) {
                return false;
            }
        }

        return true;
    });

    if (countBadge) {
        countBadge.textContent = `${filtered.length} ${filtered.length === 1 ? 'presentación' : 'presentaciones'}`;
    }

    if (filtered.length === 0) {
        grid.innerHTML = '';
        if (noResults) noResults.style.display = 'block';
        return;
    }

    if (noResults) noResults.style.display = 'none';

    grid.innerHTML = filtered.map(item => {
        const highlightedTitle = highlightMatch(item.title, queryClean);
        const highlightedSpeaker = highlightMatch(item.speaker, queryClean);
        const highlightedInst = highlightMatch(item.institution, queryClean);

        return `
            <article class="presentation-card reveal active" data-id="${item.id}" data-day="${item.day}" data-category="${item.category}">
                <div class="pres-card-header">
                    <span class="pres-day-tag day-${item.day}">${item.dayLabel}</span>
                    <span class="pres-category-tag tag-${item.category}">${item.categoryLabel}</span>
                </div>

                <div class="pres-card-body">
                    <h3 class="pres-title">${highlightedTitle}</h3>
                    
                    <div class="pres-speaker-box">
                        <div class="pres-avatar-icon">👤</div>
                        <div class="pres-speaker-details">
                            <strong class="pres-speaker-name">${highlightedSpeaker}</strong>
                            ${item.institution ? `<span class="pres-speaker-inst">🏢 ${highlightedInst}</span>` : ''}
                        </div>
                    </div>

                    <div class="pres-meta-info">
                        <span class="pres-time">🕒 Horario: <strong>${item.time}</strong></span>
                        <span class="pres-filesize">📄 PDF · ${item.size}</span>
                    </div>
                </div>

                <div class="pres-card-footer">
                    <button type="button" class="btn-view-pres" onclick="openPresentationModal('${item.id}')">
                        <span class="btn-icon">👁️</span>
                        <span>Ver Presentación</span>
                    </button>
                    <a href="${encodeURI(item.file)}" download="${item.fileName}" class="btn-download-pres" title="Descargar archivo">
                        <span class="btn-icon">⬇️</span>
                        <span class="desktop-only-text">Descargar</span>
                    </a>
                </div>
            </article>
        `;
    }).join('');
}

// Resaltar coincidencias de búsqueda
function highlightMatch(text, query) {
    if (!query || !text) return text;
    const regex = new RegExp(`(${escapeRegex(query)})`, 'gi');
    return text.replace(regex, '<mark class="search-highlight">$1</mark>');
}

function escapeRegex(string) {
    return string.replace(/[.*+?^$${}()|[\]\\]/g, '\\$&');
}

// ==========================================================================
// MOTOR DE AUTOCOMPLETADO Y SUGERENCIAS INTELIGENTES EN VIVO
// ==========================================================================
function initAutocomplete() {
    const searchInput = document.getElementById('search-presentations-input');
    const dropdown = document.getElementById('search-autocomplete-dropdown');
    const clearBtn = document.getElementById('btn-clear-search');

    if (!searchInput || !dropdown) return;

    searchInput.addEventListener('input', (e) => {
        searchQuery = searchInput.value;
        const q = searchQuery.trim().toLowerCase();

        if (clearBtn) {
            clearBtn.style.display = q ? 'flex' : 'none';
        }

        renderPresentations();

        if (q.length === 0) {
            dropdown.classList.remove('active');
            dropdown.innerHTML = '';
            selectedSuggestionIndex = -1;
            return;
        }

        // Generar sugerencias
        const suggestions = generateSuggestions(q);
        renderSuggestionsDropdown(suggestions, q);
    });

    // Limpiar búsqueda
    if (clearBtn) {
        clearBtn.addEventListener('click', () => {
            searchInput.value = '';
            searchQuery = '';
            clearBtn.style.display = 'none';
            dropdown.classList.remove('active');
            dropdown.innerHTML = '';
            searchInput.focus();
            renderPresentations();
        });
    }

    // Navegación con teclado en el autocompletado
    searchInput.addEventListener('keydown', (e) => {
        const items = dropdown.querySelectorAll('.autocomplete-item');
        if (!dropdown.classList.contains('active') || items.length === 0) {
            if (e.key === 'Enter') {
                dropdown.classList.remove('active');
            }
            return;
        }

        if (e.key === 'ArrowDown') {
            e.preventDefault();
            selectedSuggestionIndex = (selectedSuggestionIndex + 1) % items.length;
            updateSelectedSuggestion(items);
        } else if (e.key === 'ArrowUp') {
            e.preventDefault();
            selectedSuggestionIndex = (selectedSuggestionIndex - 1 + items.length) % items.length;
            updateSelectedSuggestion(items);
        } else if (e.key === 'Enter') {
            e.preventDefault();
            if (selectedSuggestionIndex >= 0 && items[selectedSuggestionIndex]) {
                items[selectedSuggestionIndex].click();
            } else {
                dropdown.classList.remove('active');
            }
        } else if (e.key === 'Escape') {
            dropdown.classList.remove('active');
        }
    });

    // Cerrar sugerencias al hacer clic fuera
    document.addEventListener('click', (e) => {
        if (!searchInput.contains(e.target) && !dropdown.contains(e.target)) {
            dropdown.classList.remove('active');
        }
    });
}

function updateSelectedSuggestion(items) {
    items.forEach((item, idx) => {
        if (idx === selectedSuggestionIndex) {
            item.classList.add('selected');
            item.scrollIntoView({ block: 'nearest' });
        } else {
            item.classList.remove('selected');
        }
    });
}

function generateSuggestions(query) {
    const speakers = new Set();
    const titles = [];
    const institutions = new Set();

    PRESENTACIONES.forEach(item => {
        // Ponente
        if (item.speaker && item.speaker.toLowerCase().includes(query)) {
            speakers.add(item.speaker);
        }
        // Título
        if (item.title && item.title.toLowerCase().includes(query)) {
            titles.push({ id: item.id, title: item.title, speaker: item.speaker, dayLabel: item.dayLabel });
        }
        // Institución
        if (item.institution && item.institution.toLowerCase().includes(query)) {
            institutions.add(item.institution);
        }
    });

    return {
        speakers: Array.from(speakers).slice(0, 4),
        titles: titles.slice(0, 5),
        institutions: Array.from(institutions).slice(0, 3)
    };
}

function renderSuggestionsDropdown(suggestions, query) {
    const dropdown = document.getElementById('search-autocomplete-dropdown');
    if (!dropdown) return;

    const hasSpeakers = suggestions.speakers.length > 0;
    const hasTitles = suggestions.titles.length > 0;
    const hasInst = suggestions.institutions.length > 0;

    if (!hasSpeakers && !hasTitles && !hasInst) {
        dropdown.innerHTML = `
            <div class="autocomplete-no-results">
                <span>🍃 No se encontraron coincidencias para "<strong>${escapeHtml(query)}</strong>"</span>
            </div>
        `;
        dropdown.classList.add('active');
        return;
    }

    let html = '';

    // Grupo Ponentes
    if (hasSpeakers) {
        html += `
            <div class="autocomplete-group-title">👤 Ponentes y Expositores</div>
            ${suggestions.speakers.map(spk => `
                <div class="autocomplete-item" onclick="selectSuggestion('${escapeHtml(spk)}')">
                    <span class="item-icon">👤</span>
                    <span class="item-text">${highlightMatch(spk, query)}</span>
                    <span class="item-badge">Ponente</span>
                </div>
            `).join('')}
        `;
    }

    // Grupo Títulos
    if (hasTitles) {
        html += `
            <div class="autocomplete-group-title">📑 Ponencias y Presentaciones</div>
            ${suggestions.titles.map(t => `
                <div class="autocomplete-item item-title-row" onclick="selectTitleSuggestion('${t.id}', '${escapeHtml(t.title)}')">
                    <span class="item-icon">📄</span>
                    <div class="item-title-content">
                        <span class="item-text item-title-text">${highlightMatch(t.title, query)}</span>
                        <small class="item-sub-meta">👤 ${t.speaker} · ${t.dayLabel}</small>
                    </div>
                </div>
            `).join('')}
        `;
    }

    // Grupo Instituciones
    if (hasInst) {
        html += `
            <div class="autocomplete-group-title">🏢 Instituciones y Entidades</div>
            ${suggestions.institutions.map(inst => `
                <div class="autocomplete-item" onclick="selectSuggestion('${escapeHtml(inst)}')">
                    <span class="item-icon">🏢</span>
                    <span class="item-text">${highlightMatch(inst, query)}</span>
                    <span class="item-badge">Institución</span>
                </div>
            `).join('')}
        `;
    }

    dropdown.innerHTML = html;
    dropdown.classList.add('active');
    selectedSuggestionIndex = -1;
}

window.selectSuggestion = function(text) {
    const searchInput = document.getElementById('search-presentations-input');
    const dropdown = document.getElementById('search-autocomplete-dropdown');
    const clearBtn = document.getElementById('btn-clear-search');

    if (searchInput) {
        searchInput.value = text;
        searchQuery = text;
        if (clearBtn) clearBtn.style.display = 'flex';
        renderPresentations();
    }
    if (dropdown) dropdown.classList.remove('active');
};

window.selectTitleSuggestion = function(presId, titleText) {
    window.selectSuggestion(titleText);
    const card = document.querySelector(`[data-id="${presId}"]`);
    if (card) {
        card.scrollIntoView({ behavior: 'smooth', block: 'center' });
        card.classList.add('highlight-pulse');
        setTimeout(() => card.classList.remove('highlight-pulse'), 2500);
    }
};

